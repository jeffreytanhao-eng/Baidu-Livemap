"""北京六环路以内粗边界（近似，WGS84）。

顶点手工取自六环走向并略微外扩，仅用于底图裁剪与引擎覆盖判定；
README 与 API meta 均注明「六环路以内区域（近似边界）」。
六环外点位由引擎按「最近全量 patch + degraded」或走廊近似兜底。
"""

from __future__ import annotations

from shapely.geometry import Point, Polygon

# 顺时针 ~18 顶点粗边界（略有外扩：边界附近的点位也能命中真实路网）
RING6_POLYGON = Polygon(
    [
        (116.100, 40.070),
        (116.200, 40.140),
        (116.330, 40.180),
        (116.460, 40.170),
        (116.580, 40.120),
        (116.660, 40.060),
        (116.710, 39.980),
        (116.720, 39.900),
        (116.700, 39.800),
        (116.660, 39.720),
        (116.550, 39.690),
        (116.420, 39.680),
        (116.300, 39.700),
        (116.190, 39.740),
        (116.120, 39.810),
        (116.060, 39.900),
        (116.050, 39.990),
        (116.070, 40.040),
    ]
)


def in_ring6(lng: float, lat: float) -> bool:
    """点是否落在六环粗边界内（含边界）。"""
    return bool(RING6_POLYGON.covers(Point(lng, lat)))
