def nearest_sample(lng: float, lat: float) -> tuple[SampleDef, float]:
    """最近的样例及其距离（米）。"""
    best = min(SAMPLES, key=lambda s: haversine_m(lng, lat, *s.center_wgs))
    return best, haversine_m(lng, lat, *best.center_wgs)


def snapshot_path(samples_dir: Path, region: str, minutes: int) -> Path:
    return samples_dir / f"{region}_{minutes}.json"
